import { existsSync } from 'node:fs';
import path from 'node:path';
import { config } from './config.js';

// «Белая марка» — снятие кнопки «Заработай на своём VPN так же».
//
// Кнопка стоит в меню каждого бота-продавца намеренно: через неё узлы приводят
// новые узлы, это канал роста франшизы. Убирается она платно и поштучно —
// первый такой случай 24.08 (узел заплатил за снятие у себя).
//
// 🔴 Почему файл, а не переменная окружения: .env бота-продавца ПЕРЕЗАПИСЫВАЕТСЯ
// целиком при каждом передеплое со станка (deploy-seller.ts, шаг 5). Флаг в нём
// молча исчез бы при первом же обновлении узла — человек заплатил, а кнопка
// вернулась. Папка данных (DATA_DIR) деплоем не трогается и переживает
// и передеплой, и самообновление.
//
// 🔴 Почему не кнопка в настройках: тогда её выключит любой узел бесплатно.
// Флаг ставится снаружи, владельцем станка, после оплаты.
const FLAG = path.join(config.dataDir, 'white-label');

/** Показывать ли кнопку «Заработай на своём VPN так же». */
export function promoEnabled(): boolean {
  return !existsSync(FLAG);
}
