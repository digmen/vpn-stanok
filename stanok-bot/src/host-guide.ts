import { kvGet } from './kv.js';

// Пошаговая покупка сервера и бонусы хостинга.
//
// 🔴 13.09, журнал станка: 28 из 70 человек нажали /start и больше ничего. Кнопка «Купить
// сервер» была голой ссылкой — ни шагов, ни того, что у хостинга есть бесплатная неделя
// и бонусы. Нажатия на ссылки Telegram боту не сообщает, поэтому кто пошёл покупать,
// тоже было не видно. Теперь «Как купить сервер» открывает экран с шагами (и это шаг
// журнала buy_open), а ссылка на хостинг — уже на нём.
//
// Промокод и текст бонусов меняются из чата админом (/promo, /bonus), без деплоя:
// условия хостинга меняются чаще, чем код станка.

export const PROMO_KEY = 'host_promo';
export const BONUS_KEY = 'host_bonus';

export function hostPromo(): string | null {
  return kvGet(PROMO_KEY);
}

/** Блок «как сэкономить». Своё слово админа (/bonus) важнее текста по умолчанию. */
export function savingsText(): string {
  const custom = kvGet(BONUS_KEY);
  if (custom) return '💸 Как сэкономить\n' + custom;
  const promo = hostPromo();
  const lines = [
    promo ? `• Неделя бесплатно новым клиентам хостинга — промокод ${promo} (вводи при оформлении).` : null,
    '• При оплате бывают скидки — смотри при оформлении заказа.',
    '• +15 дней бесплатно за отзыв о хостинге.',
  ].filter(Boolean);
  return '💸 Как сэкономить\n' + lines.join('\n');
}

export function buyGuideText(): string {
  const promo = hostPromo();
  return (
    '🛒 Как купить сервер — по шагам\n\n' +
    '1. Жми «Открыть хостинг» ниже и зарегистрируйся.\n' +
    '2. Выбери VPS, система — Ubuntu (22.04 или 24.04).\n' +
    '3. ⚠️ Отметь галочку «Выделенный IP» (~50–65 ₽). Без неё не заработает ничего — ' +
    'это причина 9 из 10 неудач. Забыл — не страшно, её можно добавить к серверу потом в панели.\n' +
    (promo ? `4. Промокод ${promo} — неделя бесплатно.\n` : '4. Оплати заказ.\n') +
    '5. Через 5–10 минут сервер готов: IP и root-пароль — в панели, в карточке сервера, ' +
    'и в письме на почту.\n' +
    '6. Вернись сюда и жми «Я купил сервер».\n\n' +
    savingsText() +
    '\n\n⚠️ Сервер работает, пока оплачен: кончится оплаченный срок — отключатся и VPN, и твой бот. ' +
    'Я напомню заранее.'
  );
}

export function renewReminderText(): string {
  return (
    '⏰ Напоминание про сервер\n\n' +
    'Твоему VPN скоро неделя. Если сервер брал на бесплатную неделю или оплатил на 7 дней — ' +
    'срок вот-вот кончится. Продли его в панели хостинга, иначе VPN и твой бот отключатся, ' +
    'а клиенты останутся без доступа.\n\n' +
    savingsText()
  );
}
