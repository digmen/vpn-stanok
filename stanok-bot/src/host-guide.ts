// Пошаговая покупка сервера.
//
// 🔴 13.09, журнал станка: 28 из 70 человек нажали /start и больше ничего. Кнопка «Купить
// сервер» была голой ссылкой — ни шагов, ни того, что сервер можно взять на 7 дней бесплатно.
// Нажатия на ссылки Telegram боту не сообщает, поэтому кто пошёл покупать, тоже было не видно.
// Теперь «Как купить сервер» открывает экран с шагами (и это шаг журнала buy_open), а ссылка
// на хостинг — уже на нём.
//
// Промокод на бесплатную неделю хостинг выдаёт каждому лично, условия живут на его сайте —
// станок их не знает и не пересказывает, чтобы не разойтись с сайтом.

export const FREE_WEEK_LINE = '🎁 Сервер можно взять на 7 дней бесплатно — промокод хостинг даёт каждому новому клиенту.';

// 17.11: для «своего VPN для себя» (personal.ts) вместо строки про бесплатную неделю — совет
// брать сразу месяц: пробный срок кончается, сервер отключают, и человек теряет свой VPN.
export function buyGuideText(mode: 'personal' | 'business' = 'business'): string {
  const personal = mode === 'personal';
  return (
    '🛒 Как купить сервер — по шагам\n\n' +
    (personal
      ? '💡 Для себя бери сервер сразу на месяц: пробные дни или неделя кончатся — и VPN отключится вместе с сервером.'
      : FREE_WEEK_LINE) +
    '\n\n' +
    '1. Жми «Открыть хостинг» ниже и зарегистрируйся.\n' +
    '2. Выбери VPS, система — Ubuntu 22.04 или 24.04 (лучше всего проверена). Подойдут и Debian, AlmaLinux, Rocky, CentOS, Fedora, openSUSE, Arch — любой обычный Linux.\n' +
    '3. ⚠️ Отметь галочку «Выделенный IP» (~50–65 ₽). Без неё не заработает ничего — ' +
    'это причина 9 из 10 неудач. Забыл — не страшно, её можно добавить к серверу потом в панели.\n' +
    '4. Оформи заказ.\n' +
    '5. Через 5–10 минут сервер готов: IP и root-пароль — в панели, в карточке сервера, ' +
    'и в письме на почту.\n' +
    '6. Вернись сюда и жми «Я купил сервер».\n\n' +
    (personal
      ? '⚠️ Сервер работает, пока оплачен: кончится срок — отключится и твой VPN. '
      : '⚠️ Сервер работает, пока оплачен: кончится срок — отключатся и VPN, и твой бот. ') +
    'Я напомню заранее.'
  );
}

export function renewReminderText(): string {
  return (
    '⏰ Напоминание про сервер\n\n' +
    'Твоему VPN скоро неделя. Если сервер брал на бесплатные 7 дней или оплатил на неделю — ' +
    'срок вот-вот кончится. Продли его в панели хостинга, иначе VPN и твой бот отключатся, ' +
    'а клиенты останутся без доступа.'
  );
}
