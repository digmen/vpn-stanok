export const FREE_WEEK_LINE = '🎁 Сервер можно взять на 7 дней бесплатно — промокод хостинг даёт каждому новому клиенту.';

export function buyGuideText(): string {
  return (
    '🛒 Как купить сервер — по шагам\n\n' +
    FREE_WEEK_LINE +
    '\n\n' +
    '1. Жми «Открыть хостинг» ниже и зарегистрируйся.\n' +
    '2. Выбери VPS, система — Ubuntu (22.04 или 24.04).\n' +
    '3. ⚠️ Отметь галочку «Выделенный IP» (~50–65 ₽). Без неё не заработает ничего — ' +
    'это причина 9 из 10 неудач. Забыл — не страшно, её можно добавить к серверу потом в панели.\n' +
    '4. Оформи заказ.\n' +
    '5. Через 5–10 минут сервер готов: IP и root-пароль — в панели, в карточке сервера, ' +
    'и в письме на почту.\n' +
    '6. Вернись сюда и жми «Я купил сервер».\n\n' +
    '⚠️ Сервер работает, пока оплачен: кончится срок — отключатся и VPN, и твой бот. ' +
    'Я напомню заранее.'
  );
}

