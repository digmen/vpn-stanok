const key = (userId: number): string => `terms:${userId}`;

/** Принимал ли человек условия (любой версии). Значение — `версия|время`. */
export function hasAcceptedTerms(userId: number): boolean {
  return kvGet(key(userId)) !== null;
}

export function acceptTerms(userId: number, now = new Date()): void {
  kvSet(key(userId), `${TERMS_VERSION}|${now.toISOString()}`);
}
